# 算数运算符 +,-,*,/,//,%,**

print(1 + 2) # 3
print(2 - 1) # 1
print(2 * 2) # 4
print(4 / 2) # 2.0
print(10 // 2) # 5
print(10 % 3) # 1
print(2 ** 3) # 8

# 复合赋值

a = 2
a += 2
print(f'加法赋值运算符：{a}')

b = 2
b -= 2
print(f'减法赋值运算符：{b}')

c = 2
c *= 2
print(f'乘法赋值运算符：{c}')

d = 2
d /= 2
print(f'除法赋值运算符：{d}')

e = 2
e %= 2
print(f'取模赋值运算符：{e}')

f = 2
f //= 2
print(f'取整除赋值运算符：{f}')

g = 2
g **= 2
print(f'幂赋值赋值运算符：{g}')


# 比较运算符，返回值是布尔值

print(2 == 2, 2 > 1, 2 < 1, 2>=1, 2<= 1)

# 逻辑运算符
print(2 and 0, 0 and 1, '2' and 1) # 真值 and 任意值，左侧为真，返回右侧。 假值 and 任意值，返回左侧值。 否则返回左侧 0、0、1
print(2 or 1, False or 0, '2' or 1) # 假值 or 任意值，左侧为真返回左侧，否则返回右侧值，2 0 2
